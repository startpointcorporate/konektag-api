import ts from 'typescript';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
const base = 'src/api/routes';
async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  return (await Promise.all(entries.map(e => e.isDirectory() ? walk(path.join(dir,e.name)) : path.join(dir,e.name)))).flat();
}
const records = [];
for (const file of (await walk(base)).filter(f => f.endsWith('.ts')).sort()) {
  const code = await readFile(file,'utf8');
  const ast = ts.createSourceFile(file,code,ts.ScriptTarget.Latest,true);
  const methods = [];
  for (const node of ast.statements) {
    if (!node.modifiers?.some(m => m.kind === ts.SyntaxKind.ExportKeyword)) continue;
    const names = ts.isVariableStatement(node) ? node.declarationList.declarations.map(d => d.name.getText(ast)) : [node.name?.getText(ast)];
    methods.push(...names.filter(n => /^(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS|ALL)$/.test(n)));
  }
  let route = '/api/' + path.relative(base,file).replace(/\.ts$/,'').replace(/(^|\/)index$/,'');
  route = route.replace(/\/$/,'');
  const segments = route.split('/').filter(Boolean);
  const pattern = '^/' + segments.map(s => /^\[\.\.\./.test(s) ? '(.*)' : /^\[/.test(s) ? '([^/]+)' : s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&')).join('/') + '/?$';
  const keys = [...route.matchAll(/\[(?:\.\.\.)?([^\]]+)\]/g)].map(m=>m[1]);
  records.push({path:route.replace(/\[(?:\.\.\.)?([^\]]+)\]/g,'{$1}'),file,methods,pattern,keys,score:segments.reduce((sum,s)=>sum+(s.startsWith('[')?0:100),0)+segments.length,code});
}
records.sort((a,b)=>b.score-a.score || a.path.localeCompare(b.path));
// Historical REST paths reuse both the handler and its canonical middleware scope.
for (const [legacy, canonical, method] of [
  ['/v1/payments', '/api/pay/payments', 'POST'],
  ['/v1/payments/{id}', '/api/pay/payments/{id}', 'GET'],
]) {
  const source = records.find(record => record.path === canonical);
  if (!source?.methods.includes(method)) throw new Error(`Missing compatibility handler: ${canonical} ${method}`);
  records.push({...source, path:legacy, methods:[method], canonicalPath:canonical,
    pattern:source.pattern.replace('/api/pay/payments', '/v1/payments')});
}
await writeFile('src/api/registry.ts','// Generated by routes.mjs from exported HTTP handlers.\nexport const routes = [\n'+records.map(r=>`  { path: ${JSON.stringify(r.path)}, pattern: new RegExp(${JSON.stringify(r.pattern)}), keys: ${JSON.stringify(r.keys)}, methods: ${JSON.stringify(r.methods)}${r.canonicalPath ? `, canonicalPath: ${JSON.stringify(r.canonicalPath)}` : ''}, load: () => import(${JSON.stringify('./routes/'+path.relative(base,r.file).replace(/\.ts$/,''))}) },`).join('\n')+'\n];\n');
await writeFile('docs/routes.json',JSON.stringify(records.map(({code,...r})=>r),null,2)+'\n');
export { records };
