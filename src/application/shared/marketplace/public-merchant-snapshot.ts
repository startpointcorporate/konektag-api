import type {ActivityCode, CertificationStatus, CommerceProfile, HotelProfile, MerchantExternalLink, MerchantMedia, MerchantOpeningHour, MerchantProduct, ProfileStatus, RestaurantProfile} from '../../../domain/MerchantProfile.ts';
export interface PublicMerchantProjection {
  id: string;
  slug: string;
  businessName: string;
  userId?: string | null;
  status?: ProfileStatus;
  activityType?: ActivityCode;
  certificationStatus?: CertificationStatus;
  logoUrl?: string;
  coverImageUrl?: string;
  shortDescription?: string;
  longDescription?: string;
  address?: string;
  city?: string;
  country?: string;
  neighborhood?: string;
  phone?: string;
  email?: string;
  websiteUrl?: string;
  publicPageUrl?: string;
  seoTitle?: string;
  seoDescription?: string;
  seoCanonicalUrl?: string;
  ogTitle?: string;
  ogDescription?: string;
  ogImageUrl?: string;
  /** PostgreSQL NUMERIC columns arrive as strings. */
  latitude?: number | string | null;
  longitude?: number | string | null;
  rating?: number | string | null;
  qrCodeUrl?: string;
  qrCodeDataUrl?: string;
  /** Generated by `loadFullProfile` for claimed profiles without a stored QR. */
  qrCodePaymentDataUrl?: string;
  restaurantProfile?: Partial<RestaurantProfile>;
  hotelProfile?: Partial<HotelProfile>;
  commerceProfile?: Partial<CommerceProfile>;
  media?: MerchantMedia[];
  externalLinks?: MerchantExternalLink[];
  openingHours?: MerchantOpeningHour[];
  products?: MerchantProduct[];
  publicationVersion?: number;
  publishedAt?: string;
  proActive?: boolean;
  isCurrentUserOwner?: boolean;
}

/** `konektag.merchant_publication_snapshots.snapshot` (schemaVersion 2). */
export interface MerchantPublicationSnapshot {
  schemaVersion?: number;
  merchant: Pick<PublicMerchantProjection,
    'id' | 'userId' | 'businessName' | 'slug' | 'logoUrl' | 'coverImageUrl' | 'shortDescription' |
    'longDescription' | 'address' | 'city' | 'country' | 'neighborhood' | 'phone' | 'latitude' |
    'longitude' | 'certificationStatus' | 'qrCodeUrl' |
    'seoTitle' | 'seoDescription' | 'seoCanonicalUrl' | 'ogTitle' | 'ogDescription' | 'ogImageUrl'> & { email?: string; websiteUrl?: string; publicPageUrl?: string };
  activityCode: ActivityCode;
  activity?: Partial<RestaurantProfile> & Partial<HotelProfile> & Partial<CommerceProfile>;
  media?: MerchantMedia[];
  externalLinks?: MerchantExternalLink[];
  openingHours?: MerchantOpeningHour[];
  products?: MerchantProduct[];
}

